const modulePath = "github.com/deploymenttheory/go-microsoft-dm"

// group is one generated package: every tree sharing a name and kind.
type group struct {
	name   string // CSP or area name as written
	pkg    string // package directory and name
	dir    string // csp/<pkg> or policy/<pkg>
	policy bool
	trees  []*csp.Tree // device first, then user, then legacy
}

// groups partitions a drop into packages, sorted by directory.
func groups(d *Drop) ([]group, error) {
	byKey := map[string]*group{}
	for _, t := range d.Trees {
		kind := "csp"
		if t.PolicyArea {
			kind = "policy"
		}
		pkg := packageName(t.Name)
		key := kind + "/" + pkg
		g, ok := byKey[key]
		if !ok {
			g = &group{name: t.Name, pkg: pkg, dir: key, policy: t.PolicyArea}
			byKey[key] = g
		} else if g.name != t.Name {
			return nil, fmt.Errorf(
				"%w: %q and %q both map to package %s",
				ErrGenerate,
				g.name,
				t.Name,
				key,
			)
		}
		g.trees = append(g.trees, t)
	}
	out := make([]group, 0, len(byKey))
	for _, g := range byKey {
		sort.SliceStable(
			g.trees,
			func(i, j int) bool { return scopeOrder(g.trees[i].Scope) < scopeOrder(g.trees[j].Scope) },
		)
		out = append(out, *g)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].dir < out[j].dir })
	return out, nil
}

func scopeOrder(s csp.Scope) int {
	switch s {
	case csp.ScopeDevice:
		return 0
	case csp.ScopeUser:
		return 1
	}
	return 2
}

// emitGroup renders the files of one package. Every exported identifier is
// appended to lock.
func emitGroup(g group, gf *GeneratedFrom, lock *[]string) (map[string][]byte, error) {
	files := map[string][]byte{}
	doc, err := gofmt(emitDoc(g, gf))
	if err != nil {
		return nil, err
	}
	files[g.dir+"/doc.gen.go"] = doc
	var tree, uris, values bytes.Buffer
	header(&tree, g.pkg, gf, `"github.com/deploymenttheory/go-microsoft-dm/schema/csp"`)
	header(&uris, g.pkg, gf, "")
	header(&values, g.pkg, gf, "")
	multi := len(g.trees) > 1
	var treeVars []string
	usedEscape := false
	for _, t := range g.trees {
		prefix := ""
		if multi {
			prefix = string(t.Scope)
		}
		treeVar := prefix + "Tree"
		if !multi {
			treeVar = "Tree"
		}
		treeVars = append(treeVars, treeVar)
		add(lock, g.dir, treeVar)
		fmt.Fprintf(
			&tree,
			"// %s is the %s root %s.\nvar %s = csp.Inherit(%s)\n\n",
			treeVar,
			t.Scope,
			t.Root.URI,
			treeVar,
			treeLiteral(t),
		)
		rootConst := prefix + "Root"
		if !multi {
			rootConst = "Root"
		}
		add(lock, g.dir, rootConst)
		fmt.Fprintf(
			&uris,
			"// %s is the %s root of %s.\nconst %s = %q\n\n",
			rootConst,
			t.Scope,
			g.name,
			rootConst,
			t.Root.URI,
		)
		for _, n := range nameNodes(t, prefix) {
			if len(n.params) > 0 {
				usedEscape = true
			}
			emitURI(&uris, n, lock, g.dir)
			emitValues(&values, n, lock, g.dir)
		}
	}
	if usedEscape {
		uris.WriteString(
			"// escape encodes one dynamic segment for a LocURI.\nfunc escape(s string) string { return url.PathEscape(s) }\n",
		)
		b := uris.Bytes()
		uris.Reset()
		uris.Write(
			bytes.Replace(
				b,
				[]byte("\npackage "+g.pkg+"\n\n"),
				[]byte("\npackage "+g.pkg+"\n\nimport \"net/url\"\n\n"),
				1,
			),
		)
	}
	add(lock, g.dir, "Trees")
	fmt.Fprintf(
		&tree,
		"// Trees lists every root of %s in this package.\nvar Trees = []*csp.Tree{%s}\n",
		g.name,
		strings.Join(treeVars, ", "),
	)
	for name, buf := range map[string]*bytes.Buffer{"tree.gen.go": &tree, "uris.gen.go": &uris, "values.gen.go": &values} {
		if name == "values.gen.go" && !bytes.Contains(buf.Bytes(), []byte("\nconst ")) {
			continue
		}
		out, err := gofmt(buf.Bytes())
		if err != nil {
			return nil, fmt.Errorf("%w: %s/%s: %w", ErrGenerate, g.dir, name, err)
		}
		files[g.dir+"/"+name] = out
	}
	return files, nil
}

func add(lock *[]string, dir, ident string) { *lock = append(*lock, dir+"/"+ident) }

func header(w *bytes.Buffer, pkg string, gf *GeneratedFrom, imports string) {
	fmt.Fprintf(
		w,
		"// Code generated by ddfgen; DO NOT EDIT.\n// Source: %s (sha256 %s)\n\npackage %s\n\n",
		gf.Bundle,
		gf.SHA256[:12],
		pkg,
	)
	if imports != "" {
		fmt.Fprintf(w, "import %s\n\n", imports)
	}
}

func emitDoc(g group, gf *GeneratedFrom) []byte {
	var b bytes.Buffer
	kind := "configuration service provider"
	ref := "https://learn.microsoft.com/en-us/windows/client-management/mdm/" + strings.ToLower(
		g.name,
	) + "-csp"
	if g.policy {
		kind = "Policy CSP area"
		ref = "https://learn.microsoft.com/en-us/windows/client-management/mdm/policy-csp-" + strings.ToLower(
			strings.TrimPrefix(g.name, "ADMX_"),
		)
		if strings.HasPrefix(g.name, "ADMX_") {
			ref = "https://learn.microsoft.com/en-us/windows/client-management/mdm/policy-csp-" + strings.ToLower(
				strings.ReplaceAll(g.name, "_", "-"),
			)
		}
	}
	nodes := 0
	roots := make([]string, 0, len(g.trees))
	for _, t := range g.trees {
		nodes += len(t.Nodes())
		roots = append(roots, t.Root.URI)
	}
	fmt.Fprintf(
		&b,
		"// Code generated by ddfgen; DO NOT EDIT.\n// Source: %s (sha256 %s)\n\n",
		gf.Bundle,
		gf.SHA256[:12],
	)
	fmt.Fprintf(
		&b,
		"// Package %s describes the %s %s: %d nodes under %s.\n//\n",
		g.pkg,
		g.name,
		kind,
		nodes,
		strings.Join(roots, " and "),
	)
	fmt.Fprintf(
		&b,
		"// # Design\n//\n// Generated from %s in Microsoft's DDF v2 bundle %s. Tree holds every node with\n// its format, access, applicability and allowed values; the URI constants and\n// functions name each node, with a function parameter for every dynamic\n// segment; the value constants name each ENUM and Flag entry. Nothing here is\n// edited by hand: change the generator and run make generate.\n//\n",
		g.trees[0].File,
		gf.Bundle,
	)
	fmt.Fprintf(
		&b,
		"// # References\n//\n//   - Decision record 0006: https://github.com/deploymenttheory/go-microsoft-dm/blob/main/docs/research/decisions/0006-schema-generator-over-ddf-v2.md\n//   - Microsoft: %s\n//   - Microsoft, DDF files: https://learn.microsoft.com/en-us/windows/client-management/mdm/configuration-service-provider-ddf\npackage %s\n",
		ref,
		g.pkg,
	)
	return b.Bytes()
}

func emitURI(w *bytes.Buffer, n named, lock *[]string, dir string) {
	desc := firstSentence(n.node.Description)
	if desc == "" {
		desc = n.node.URI
	}
	add(lock, dir, n.scoped)
	if len(n.params) == 0 {
		fmt.Fprintf(
			w,
			"// %s is %s.\n// %s\nconst %s = %q\n\n",
			n.scoped,
			n.node.URI,
			desc,
			n.scoped,
			n.node.URI,
		)
		return
	}
	params := paramList(n)
	var sig []string
	for _, p := range params {
		sig = append(sig, p+" string")
	}
	fmt.Fprintf(
		w,
		"// %s is %s.\n// %s\nfunc %s(%s) string {\n\treturn %s\n}\n\n",
		n.scoped,
		n.node.URI,
		desc,
		n.scoped,
		strings.Join(sig, ", "),
		uriExpr(n, params),
	)
}

// uriExpr renders the template with url.PathEscape on each parameter.
func uriExpr(n named, params []string) string {
	var parts []string
	var lit strings.Builder
	pi := 0
	for i, seg := range strings.Split(n.node.URI, "/") {
		if i > 0 {
			lit.WriteString("/")
		}
		if len(seg) > 2 && seg[0] == '{' && seg[len(seg)-1] == '}' {
			parts = append(parts, strconv.Quote(lit.String()), "escape("+params[pi]+")")
			pi++
			lit.Reset()
			continue
		}
		lit.WriteString(seg)
	}
	if lit.Len() > 0 {
		parts = append(parts, strconv.Quote(lit.String()))
	}
	return strings.Join(parts, " + ")
}

func emitValues(w *bytes.Buffer, n named, lock *[]string, dir string) {
	av := n.node.AllowedValues
	if av == nil || (av.Type != csp.ValueTypeEnum && av.Type != csp.ValueTypeFlag) ||
		len(av.Enum) == 0 {
		return
	}
	fmt.Fprintf(w, "// %s values (%s).\nconst (\n", n.scoped, av.Type)
	seen := map[string]int{}
	for _, e := range av.Enum {
		id := enumIdent(e)
		if k := seen[id]; k > 0 {
			id = fmt.Sprintf("%s%d", id, k+1)
		}
		seen[enumIdent(e)]++
		name := n.scoped + id
		add(lock, dir, name)
		if d := strings.Join(strings.Fields(e.Description), " "); d != "" {
			fmt.Fprintf(w, "\t// %s\n", d)
		}
		fmt.Fprintf(w, "\t%s = %q\n", name, e.Value)
	}
	fmt.Fprint(w, ")\n\n")
}

func firstSentence(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if i := strings.Index(s, ". "); i > 0 && i < 200 {
		return s[:i+1]
	}
	if len(s) > 200 {
		return s[:200] + "..."
	}
	return s
}

func gofmt(src []byte) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("gofmt: %w\n%s", err, src)
	}
	return out, nil
}

// treeLiteral renders a csp.Tree as a Go composite literal.
func treeLiteral(t *csp.Tree) string {
	var b strings.Builder
	fmt.Fprintf(
		&b,
		"&csp.Tree{Name: %q, File: %q, Scope: %q, PolicyArea: %v, Root: ",
		t.Name,
		t.File,
		string(t.Scope),
		t.PolicyArea,
	)
	nodeLiteral(&b, t.Root, nil, 1)
	b.WriteString("}")
	return b.String()
}

func nodeLiteral(b *strings.Builder, n *csp.Node, parentApp *csp.Applicability, depth int) {
	ind := strings.Repeat("\t", depth)
	fmt.Fprintf(
		b,
		"&csp.Node{\n%sName: %q, URI: %q, Format: %q,\n",
		ind,
		n.Name,
		n.URI,
		string(n.Format),
	)
	if n.Title != "" {
		fmt.Fprintf(b, "%sTitle: %q,\n", ind, n.Title)
	}
	if len(n.Access) > 0 {
		acc := make([]string, 0, len(n.Access))
		for _, a := range n.Access {
			acc = append(acc, strconv.Quote(string(a)))
		}
		fmt.Fprintf(b, "%sAccess: []csp.Access{%s},\n", ind, strings.Join(acc, ", "))
	}
	if n.Description != "" {
		fmt.Fprintf(b, "%sDescription: %q,\n", ind, n.Description)
	}
	if n.Default != "" {
		fmt.Fprintf(b, "%sDefault: %q,\n", ind, n.Default)
	}
	if n.Occurrence != "" {
		fmt.Fprintf(b, "%sOccurrence: %q,\n", ind, n.Occurrence)
	}
	if n.Permanent {
		fmt.Fprintf(b, "%sPermanent: true,\n", ind)
	}
	if n.MIME != "" {
		fmt.Fprintf(b, "%sMIME: %q,\n", ind, n.MIME)
	}
	if n.CaseSensitive {
		fmt.Fprintf(b, "%sCaseSensitive: true,\n", ind)
	}
	if n.Dynamic {
		fmt.Fprintf(b, "%sDynamic: true,\n", ind)
	}
	if n.Naming.Kind != "" {
		fmt.Fprintf(
			b,
			"%sNaming: csp.Naming{Kind: %q, Pattern: %q},\n",
			ind,
			string(n.Naming.Kind),
			n.Naming.Pattern,
		)
	}
	if n.Applicability != nil && n.OwnApplicability {
		a := n.Applicability
		fmt.Fprintf(
			b,
			"%sOwnApplicability: true,\n%sApplicability: &csp.Applicability{OsBuildVersions: %s, CspVersion: %q, EditionAllowList: %s, RequiresAzureAd: %v},\n",
			ind,
			ind,
			stringSlice(a.OsBuildVersions),
			a.CspVersion,
			stringSlice(a.EditionAllowList),
			a.RequiresAzureAd,
		)
	}
	if n.AllowedValues != nil {
		fmt.Fprintf(b, "%sAllowedValues: %s,\n", ind, allowedLiteral(n.AllowedValues))
	}
	if n.GpMapping != nil {
		fmt.Fprintf(
			b,
			"%sGpMapping: &csp.GpMapping{EnglishName: %q, AreaPath: %q, Element: %q},\n",
			ind,
			n.GpMapping.EnglishName,
			n.GpMapping.AreaPath,
			n.GpMapping.Element,
		)
	}
	if n.ConflictResolution != "" {
		fmt.Fprintf(b, "%sConflictResolution: %q,\n", ind, n.ConflictResolution)
	}
	if n.ReplaceBehavior != "" {
		fmt.Fprintf(b, "%sReplaceBehavior: %q,\n", ind, n.ReplaceBehavior)
	}
	if n.RebootBehavior != "" {
		fmt.Fprintf(b, "%sRebootBehavior: %q,\n", ind, n.RebootBehavior)
	}
	if n.AtomicRequired {
		fmt.Fprintf(b, "%sAtomicRequired: true,\n", ind)
	}
	if n.Deprecated != nil {
		fmt.Fprintf(
			b,
			"%sDeprecated: &csp.Deprecated{OsBuildDeprecated: %q},\n",
			ind,
			n.Deprecated.OsBuildDeprecated,
		)
	}
	if len(n.Dependencies) > 0 {
		fmt.Fprintf(b, "%sDependencies: []csp.DependencyGroup{", ind)
		for _, g := range n.Dependencies {
			fmt.Fprintf(b, "{FriendlyID: %q", g.FriendlyID)
			if g.ChangedAllowedValues != nil {
				fmt.Fprintf(b, ", ChangedAllowedValues: %s", allowedLiteral(g.ChangedAllowedValues))
			}
			b.WriteString(", Dependencies: []csp.Dependency{")
			for _, d := range g.Dependencies {
				fmt.Fprintf(
					b,
					"{Type: %q, URI: %q, ValueType: %q, Value: %q, Enum: %s}, ",
					d.Type,
					d.URI,
					string(d.ValueType),
					d.Value,
					enumLiteral(d.Enum),
				)
			}
			b.WriteString("}}, ")
		}
		b.WriteString("},\n")
	}
	if len(n.Children) > 0 {
		fmt.Fprintf(b, "%sChildren: []*csp.Node{\n", ind)
		for _, c := range n.Children {
			b.WriteString(ind + "\t")
			nodeLiteral(b, c, n.Applicability, depth+1)
			b.WriteString(",\n")
		}
		fmt.Fprintf(b, "%s},\n", ind)
	}
	b.WriteString(strings.Repeat("\t", depth-1) + "}")
}

func allowedLiteral(av *csp.AllowedValues) string {
	admx := "nil"
	if av.ADMX != nil {
		admx = fmt.Sprintf(
			"&csp.ADMX{Area: %q, Name: %q, File: %q}",
			av.ADMX.Area,
			av.ADMX.Name,
			av.ADMX.File,
		)
	}
	return fmt.Sprintf(
		"&csp.AllowedValues{Type: %q, Value: %q, Enum: %s, ADMX: %s, ListDelimiter: %q}",
		string(av.Type),
		av.Value,
		enumLiteral(av.Enum),
		admx,
		av.ListDelimiter,
	)
}

func enumLiteral(es []csp.EnumValue) string {
	if len(es) == 0 {
		return "nil"
	}
	var parts []string
	for _, e := range es {
		parts = append(parts, fmt.Sprintf("{Value: %q, Description: %q}", e.Value, e.Description))
	}
	return "[]csp.EnumValue{" + strings.Join(parts, ", ") + "}"
}

func stringSlice(ss []string) string {
	if len(ss) == 0 {
		return "nil"
	}
	q := make([]string, len(ss))
	for i, s := range ss {
		q[i] = strconv.Quote(s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

// emitRegistry renders schema/registry, which imports every generated
// package and joins their trees.
func emitRegistry(gs []group, gf *GeneratedFrom) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(
		&b,
		"// Code generated by ddfgen; DO NOT EDIT.\n// Source: %s (sha256 %s)\n\n",
		gf.Bundle,
		gf.SHA256[:12],
	)
	fmt.Fprintf(
		&b,
		"// Package registry joins every generated CSP and Policy area tree from\n// Microsoft's DDF v2 bundle %s into one csp.Registry: %d packages, %d trees,\n// %d nodes.\n//\n// # Design\n//\n// Importing this package links every generated tree. A consumer that needs one\n// CSP imports that package instead. Lookup is csp.Registry.Lookup over all\n// trees; Registry constructs the registry once.\n//\n// # References\n//\n//   - Decision record 0006: https://github.com/deploymenttheory/go-microsoft-dm/blob/main/docs/research/decisions/0006-schema-generator-over-ddf-v2.md\npackage registry\n\n",
		gf.Bundle,
		len(gs),
		gf.Trees,
		gf.Nodes,
	)
	b.WriteString(
		"import (\n\t\"sync\"\n\n\t\"github.com/deploymenttheory/go-microsoft-dm/schema/csp\"\n",
	)
	for _, g := range gs {
		alias := strings.ReplaceAll(g.dir, "/", "_")
		fmt.Fprintf(&b, "\t%s \"%s/schema/%s\"\n", alias, modulePath, g.dir)
	}
	b.WriteString(
		")\n\nvar once sync.Once\nvar reg *csp.Registry\n\n// Trees returns every generated tree: standalone CSPs first, then Policy areas, each sorted by package.\nfunc Trees() []*csp.Tree {\n\tvar out []*csp.Tree\n",
	)
	for _, g := range gs {
		fmt.Fprintf(&b, "\tout = append(out, %s.Trees...)\n", strings.ReplaceAll(g.dir, "/", "_"))
	}
	b.WriteString(
		"\treturn out\n}\n\n// Registry returns the registry over Trees, built once.\nfunc Registry() *csp.Registry {\n\tonce.Do(func() { reg = csp.NewRegistry(Trees()...) })\n\treturn reg\n}\n\n// Lookup resolves a concrete OMA-URI across every tree.\nfunc Lookup(uri string) (csp.Match, *csp.Tree, bool) { return Registry().Lookup(uri) }\n",
	)
	return gofmt(b.Bytes())
}
